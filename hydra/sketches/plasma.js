// plasma — oscillators warped through noise and themselves; molten, ever-shifting color.
const h = rand()
osc(4, 0.08, 1.4)
  .modulate(noise(2.5, 0.06).add(osc(5, 0.05).rotate(1.2), 0.5), 1.1)
  .modulateRotate(osc(1.5, 0.02), 0.8)
  .colorama(() => 0.02)
  .hue(h)
  .saturate(1.5)
  .contrast(1.25)
  .out(o0)
